async function main() {
  console.log('--- Seeding Comprehensive 150-Word Official Starter Library ---');

  for (const def of officialDecksData) {
    const deck = await prisma.officialDeck.upsert({
      where: { slug: def.slug },
      update: {
        title: def.title,
        titleVi: def.titleVi,
        description: def.description,
        pathCode: def.pathCode,
        level: def.level,
        order: def.order,
        listCode: def.listCode,
        cardCount: def.cards.length,
      },
      create: {
        slug: def.slug,
        title: def.title,
        titleVi: def.titleVi,
        description: def.description,
        pathCode: def.pathCode,
        level: def.level,
        order: def.order,
        listCode: def.listCode,
        cardCount: def.cards.length,
      },
    });

    console.log(`Upserted deck: [${deck.pathCode}] ${deck.title} (${def.cards.length} cards)`);

    // Clean existing cards for this deck to avoid duplicates upon re-seeding
    const existingDeckCards = await prisma.officialDeckCard.findMany({
      where: { deckId: deck.id },
      select: { cardId: true },
    });

    if (existingDeckCards.length > 0) {
      await prisma.officialDeckCard.deleteMany({
        where: { deckId: deck.id },
      });
      await prisma.officialCard.deleteMany({
        where: {
          id: { in: existingDeckCards.map((c) => c.cardId) },
        },
      });
    }

    let orderIdx = 1;
    for (const cardData of def.cards) {
      const contentJson = {
        word: cardData.word,
        pos: cardData.pos,
        ipa_us: cardData.ipa,
        meaning_vi: cardData.meaningVi,
        definition_en: cardData.defEn,
        example_en: cardData.exampleEn,
        example_vi: cardData.exampleVi,
        collocations: cardData.collocations,
        mnemonic: cardData.mnemonic,
      };

      const officialCard = await prisma.officialCard.create({
        data: {
          headword: cardData.word,
          pos: cardData.pos,
          content: contentJson,
          status: 'PUBLISHED',
          contentVersion: 1,
        },
      });

      await prisma.officialDeckCard.create({
        data: {
          deckId: deck.id,
          cardId: officialCard.id,
          order: orderIdx++,
        },
      });
    }
  }

  const deckCount = await prisma.officialDeck.count();
  const cardCount = await prisma.officialCard.count();
  console.log(`\n🎉 Successfully seeded ${deckCount} Official Decks and ${cardCount} Official Cards!`);
}

main()
  .catch((e) => {
    console.error('Seeding error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
    await pool.end();
  });
